@server.call_tool()
async def call_tool(name: str, arguments: Dict[str, Any]) -> List[TextContent]:
    """处理工具调用"""
    _ensure_dirs()
    
    try:
        if name == "create_plan":
            return await _handle_create_plan(arguments)
        elif name == "read_plan":
            return await _handle_read_plan(arguments)
        elif name == "update_plan":
            return await _handle_update_plan(arguments)
        elif name == "create_spec":
            return await _handle_create_spec(arguments)
        elif name == "read_spec":
            return await _handle_read_spec(arguments)
        elif name == "update_spec":
            return await _handle_update_spec(arguments)
        elif name == "list_plans":
            return await _handle_list_plans(arguments)
        elif name == "list_specs":
            return await _handle_list_specs(arguments)
        elif name == "delete_document":
            return await _handle_delete_document(arguments)
        else:
            raise ValueError(f"未知工具: {name}")
    except Exception as e:
        return [TextContent(
            type="text",
            text=fast_json_dumps({
                "success": False,
                "error": str(e),
                "error_type": type(e).__name__
            }, ensure_ascii=False)
        )]


# ============== Plan 模式处理函数 ==============

async def _handle_create_plan(args: Dict[str, Any]) -> List[TextContent]:
    """创建规划文档"""
    title = args["title"]
    description = args["description"]
    goals = args["goals"]
    steps = args["steps"]
    criteria = args["criteria"]
    notes = args.get("notes", "")
    output_path = args.get("output_path")
    
    # 生成内容
    content = PLAN_TEMPLATE.format(
        title=title,
        description=description,
        goals=goals,
        steps=steps,
        criteria=criteria,
        notes=notes,
        created_at=datetime.now().isoformat()
    )
    
    # 确定输出路径
    if not output_path:
        safe_title = "".join(c if c.isalnum() or c in "-_" else "_" for c in title)
        output_path = os.path.join(PLANS_DIR, f"plan_{safe_title}.md")
    
    if not output_path.endswith('.md'):
        output_path += '.md'
    
    # 验证路径
    output_path = _validate_path(output_path, [PLANS_DIR, SPECS_DIR, "."])
    
    # 确保目录存在
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    
    # 写入文件
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(content)
    
    return [TextContent(
        type="text",
        text=fast_json_dumps({
            "success": True,
            "file_path": output_path,
            "file_name": os.path.basename(output_path),
            "title": title,
            "created_at": datetime.now().isoformat()
        }, ensure_ascii=False, indent=2)
    )]


async def _handle_read_plan(args: Dict[str, Any]) -> List[TextContent]:
    """读取规划文档"""
    plan_path = args["plan_path"]
    
    # 验证路径
    plan_path = _validate_path(plan_path, [PLANS_DIR, SPECS_DIR, "."])
    
    if not os.path.exists(plan_path):
        raise FileNotFoundError(f"规划文件不存在: {plan_path}")
    
    with open(plan_path, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # 解析章节
