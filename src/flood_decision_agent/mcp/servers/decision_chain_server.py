def _validate_path(path: str, allowed_dirs: List[str]) -> str:
    """验证路径是否在允许范围内"""
    abs_path = os.path.abspath(path)
    for allowed in allowed_dirs:
        if abs_path.startswith(os.path.abspath(allowed)):
            return abs_path
    raise ValueError(f"路径不在允许范围内: {path}")


